def extract_array(source: str) -> str:
    """ SUPPORT_PROVIDERS 配列の中身を取り出す """
    match = re.search(r'export\s+const\s+SUPPORT_PROVIDERS\s*:[^=]*=\s*\[', source)
    if match is None:
        raise ValueError('SUPPORT_PROVIDERS is not found.')
    depth = 1
    pos = match.end()
    quote = ''
    while pos < len(source):
        c = source[pos]
        if quote:
            if c == '\\':
                pos += 1
            elif c == quote:
                quote = ''
        elif c in ('\'', '"', '`'):
            quote = c
        elif c == '[':
            depth += 1
        elif c == ']':
            depth -= 1
            if depth == 0:
                return source[match.end():pos]
        pos += 1
    raise ValueError('The end of SUPPORT_PROVIDERS is not found.')


def parse_string_value(item: str, key: str):
    match = re.search(r'\b' + key + r'\s*:\s*(\'(?:[^\'\\]|\\.)*\'|"(?:[^"\\]|\\.)*")', item)
    if match is None:
        return None
    value = match.group(1)[1:-1]
    return re.sub(r'\\(.)', r'\1', value)


def parse_providers(source: str) -> list:
    body = extract_array(source)
    # コメントを除去
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.DOTALL)
    body = re.sub(r'^\s*//.*$', '', body, flags=re.MULTILINE)
    providers = []
    for item in re.findall(r'\{([^{}]*)\}', body):
        name = parse_string_value(item, 'name')
        logo = parse_string_value(item, 'logo')
        domain = parse_string_value(item, 'domain')
        if name is None or logo is None or domain is None:
            raise ValueError('name, logo or domain is not found : ' + item.strip())
        if re.fullmatch(r'[A-Za-z0-9_]+', logo) is None:
            raise ValueError('Invalid logo name : ' + logo)
        providers.append({
            'name': name,
            'logo': logo,
            'domain': domain.lower(),
            'path_prefix': parse_string_value(item, 'pathPrefix'),
        })
    if len(providers) == 0:
        raise ValueError('SUPPORT_PROVIDERS is empty.')
    return providers


def unique_logos(providers: list) -> list:
    return sorted(set(provider['logo'] for provider in providers))


def to_cpp_string(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def detect_newline(text: str) -> str:
    return '\r\n' if '\r\n' in text else '\n'


def make_cpp(current: str, providers: list) -> str:
    lines = current.splitlines(keepends=True)
    begin = -1
    end = -1
    for i, line in enumerate(lines):
        if line.startswith(BEGIN_MARKER):
            begin = i
        elif line.startswith(END_MARKER):
            end = i
    if begin < 0 or end < 0 or end < begin:
        raise ValueError('The markers are not found in supportprovider.cpp.')
    newline = detect_newline(lines[begin])
    table = ['const ProviderRule SUPPORT_PROVIDERS[] = {' + newline]
    for provider in providers:
        path_prefix = 'nullptr'
        if provider['path_prefix'] is not None:
            path_prefix = to_cpp_string(provider['path_prefix'])
        table.append('    { %s, %s, %s, %s },%s' % (to_cpp_string(provider['name']),
                                                    to_cpp_string(provider['logo']),
                                                    to_cpp_string(provider['domain']),
                                                    path_prefix, newline))
    table.append('};' + newline)
    return ''.join(lines[:begin + 1] + table + lines[end:])


def make_readme(source_readme: str, providers: list) -> str:
    """ 元のREADMEから使用するアイコンの権利者の行を抜き出して羽衣用のREADMEを作る """
    rows = []
    for logo in unique_logos(providers):
        file_name = logo + '.svg'
        holder = None
        for line in source_readme.splitlines():
            cells = [cell.strip() for cell in line.strip().strip('|').split('|')]
            if len(cells) == 2 and ('`%s`' % file_name) in cells[0]:
                holder = cells[1]
                break
        if holder is None:
            # 元のREADMEに記載のないアイコンはproviders.tsの情報で補う
            provider = [p for p in providers if p['logo'] == logo][0]
            holder = '[%s](https://%s)' % (provider['name'], provider['domain'])
            print('Warning : %s is not listed in the README of social-app.' % (file_name, ))
        rows.append('| `%s` | %s |\n' % (file_name, holder))
    return README_HEADER + ''.join(rows) + README_FOOTER


def make_qrc(current: str, providers: list) -> str:
    lines = current.splitlines(keepends=True)
    newline = detect_newline(current)
    insert_pos = -1
    indent = '        '
    result = []
    for line in lines:
        if QRC_ICON_PREFIX in line:
            # 既存のエントリは作り直す
            if insert_pos < 0:
                insert_pos = len(result)
            continue
        if '<file>qml/images/' in line:
            indent = line[:len(line) - len(line.lstrip())]
        result.append(line)
    if insert_pos < 0:
        # 初回は qml/images/ の最後のエントリの後ろへ追加
        for i, line in enumerate(result):
            if '<file>qml/images/' in line:
                insert_pos = i + 1
        if insert_pos < 0:
            raise ValueError('qml/images/ entries are not found in app.qrc.')
    entries = ['%s<file>%s%s.svg</file>%s' % (indent, QRC_ICON_PREFIX, logo, newline)
               for logo in unique_logos(providers)]
    return ''.join(result[:insert_pos] + entries + result[insert_pos:])


def read_text(path: str) -> str:
    with open(path, 'r', encoding='utf-8', newline='') as fp:
        return fp.read()


def read_bytes(path: str):
    if not os.path.isfile(path):
        return None
    with open(path, 'rb') as fp:
        return fp.read()


if __name__ == "__main__":
    base_dir: str = os.path.dirname(os.path.abspath(__file__))
    root_dir: str = os.path.dirname(base_dir)
    social_app_dir: str = os.path.join(root_dir, '1stparty/social-app')

    parser = argparse.ArgumentParser(description='Generate the support provider table and icons from providers.ts.')
    parser.add_argument('--social-app', default=social_app_dir,
                        help='path/to/social-app')
    parser.add_argument('--root', default=root_dir,
                        help='path/to/Hagoromo')
    parser.add_argument('--check', action='store_true',
                        help='do not write, exit with 1 if any output is out of date')
    args = parser.parse_args()

    providers_ts = os.path.join(args.social_app, 'src/features/profileLinks/providers.ts')
    icons_dir = os.path.join(args.social_app, 'assets/icons/community')
    cpp_path = os.path.join(args.root, 'lib/tools/supportprovider.cpp')
    qrc_path = os.path.join(args.root, 'app/app.qrc')
    out_icons_dir = os.path.join(args.root, 'app/qml/images/community')

    # 出力ファイルのパスと内容（bytes）
    outputs = {}
    try:
        providers = parse_providers(read_text(providers_ts))
        outputs[cpp_path] = make_cpp(read_text(cpp_path), providers).encode('utf-8')
        outputs[qrc_path] = make_qrc(read_text(qrc_path), providers).encode('utf-8')
        readme = make_readme(read_text(os.path.join(icons_dir, 'README.md')), providers)
        outputs[os.path.join(out_icons_dir, 'README.md')] = readme.encode('utf-8')
        for logo in unique_logos(providers):
            svg = read_bytes(os.path.join(icons_dir, logo + '.svg'))
            if svg is None:
                raise ValueError('%s.svg is not found in %s.' % (logo, icons_dir))
            outputs[os.path.join(out_icons_dir, logo + '.svg')] = svg
    except (OSError, ValueError) as e:
        print('Error : %s' % (e, ))
        sys.exit(2)

    # 使われなくなったアイコン
    removes = []
    if os.path.isdir(out_icons_dir):
        for name in sorted(os.listdir(out_icons_dir)):
            path = os.path.join(out_icons_dir, name)
            if path not in outputs:
                removes.append(path)

    changes = [path for path, data in outputs.items() if read_bytes(path) != data]

    if len(changes) == 0 and len(removes) == 0:
        print('OK : Support providers are up to date. (%d providers, %d icons)'
              % (len(providers), len(unique_logos(providers))))
        sys.exit(0)
    if args.check:
        for path in changes:
            print('NG : %s is out of date.' % (os.path.relpath(path, args.root), ))
        for path in removes:
            print('NG : %s is not used.' % (os.path.relpath(path, args.root), ))
        print('Run scripts/update_support_providers.py.')
        sys.exit(1)

    os.makedirs(out_icons_dir, exist_ok=True)
    for path in changes:
        with open(path, 'wb') as fp:
            fp.write(outputs[path])
        print('Updated : %s' % (os.path.relpath(path, args.root), ))
    for path in removes:
        os.remove(path)
        print('Removed : %s' % (os.path.relpath(path, args.root), ))
